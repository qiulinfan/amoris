    #[test]
    fn radii_follow_their_power_law() {
        // With both slopes 2 between 1 and 4 mm, half the bubbles lie under 1.6 mm (the median
        // of r^-2 there is 1/(1/1 - (1/1 - 1/4)/2) = 1.6 mm).
        let mut below = 0;
        let n = 20_000;
        let mut random = Random(7);
        for _ in 0..n {
            let r = radius(random.unit(), (1e-3, 4e-3), (2.0, 2.0));
            assert!((1e-3..=4e-3).contains(&r));
            if r < 1.6e-3 {
                below += 1;
            }
        }
        let share = below as f32 / n as f32;
        assert!((share - 0.5).abs() < 0.02, "{share}");
        // Two slopes join continuously: the density just under and over 1 mm agree.
        let mut random = Random(9);
        let (mut under, mut over) = (0, 0);
        for _ in 0..200_000 {
            let r = radius(random.unit(), (0.5e-3, 2e-3), (1.5, 10.0 / 3.0));
            if (0.95e-3..1e-3).contains(&r) {
                under += 1;
            } else if (1e-3..1.05e-3).contains(&r) {
                over += 1;
            }
        }
        let ratio = under as f32 / over as f32;
        assert!((ratio - 1.0).abs() < 0.15, "{under} under, {over} over");
    }

    /// One bubble alone rings at its Minnaert frequency and decays at van den Doel's rate.
    #[test]
    fn a_bubble_rings_at_its_frequency_and_dies_away() {
        let mut synth = WaterSynth::new(48_000, 3);
        let r = 2e-3;
        let (f0, d) = (minnaert(r), damping(r));
        let w = TAU * f0 / 48_000.0;
        let q = (-2.0 * d / 48_000.0).exp();
        // Small, so the output's gentle limit stays linear.
        synth.bubbles.push(Bubble {
            y1: 0.01 * q.sqrt() * w.sin(),
            q,
            c: 2.0 * q.sqrt() * w.cos(),
            f0,
            left: 1.0,
            right: 1.0,
            remaining: 48_000,
            ..Bubble::default()
        });
        let mut out = vec![[0.0f32; 2]; 4800];
        synth.render(&mut out);
        let x: Vec<f32> = out.iter().map(|f| f[0]).collect();
        // Zero crossings over the first 20 ms give the frequency.
        let crossings = x[..960]
            .windows(2)
            .filter(|p| p[0] <= 0.0 && p[1] > 0.0)
            .count();
        let measured = crossings as f32 / 0.02;
        assert!(
            (measured - f0).abs() < 0.05 * f0,
            "{measured} Hz against {f0}"
        );
        // Peak amplitude over successive 2 ms windows decays as e^(-d t).
        let peak = |i: usize| x[i..i + 96].iter().fold(0.0f32, |m, v| m.max(v.abs()));
        let (a, b) = (peak(96), peak(96 + 480));
        let rate = (a / b).ln() / 0.01;
        assert!((rate - d).abs() < 0.08 * d, "decays at {rate} against {d}");
    }

    /// Doubling a source's events doubles the sound's power; its sides follow the ears' energy;
    /// nothing sounds without events. Landing drops: narrow radii, and tens of thousands of
    /// bubbles, as each bubble's energy is far from even (`D^2 r^(2 EXPONENT) / 4d`).
    #[test]
    fn power_follows_the_events_and_the_ears() {
        let power = |sources: [WaterSource; KINDS], seed: u32| {
            let mut synth = WaterSynth::new(48_000, seed);
            synth.set(sources);
            let mut out = vec![[0.0f32; 2]; 48_000 * 3];
            synth.render(&mut out);
            let tail = &out[48_000..];
            let n = tail.len() as f32;
            (
                tail.iter().map(|f| f[0] * f[0]).sum::<f32>() / n,
                tail.iter().map(|f| f[1] * f[1]).sum::<f32>() / n,
            )
        };
        let drops = |rate: f32, left: f32, right: f32| {
            let mut s = quiet();
            s[5] = WaterSource { rate, left, right };
            s
        };
        let mean = |s: [WaterSource; KINDS]| (0..6).map(|seed| power(s, seed).0).sum::<f32>() / 6.0;
        let (p1, p2) = (mean(drops(4000.0, 4.0, 4.0)), mean(drops(8000.0, 8.0, 8.0)));
        assert!(
            (p2 / p1 - 2.0).abs() < 0.15,
            "{p1} then {p2}: the ratio {}",
            p2 / p1
        );
        let (l, r) = power(drops(500.0, 1.0, 0.0), 1);
        assert!(l > 4.0 * r, "left {l}, right {r}");
        assert_eq!(power(quiet(), 1), (0.0, 0.0));
    }

    /// Every kind sounds the power its tally gives, whatever its radii: its bubbles' energies,
    /// a^2 / 4d at both ears, add up to the level's square times the tally's watts a square metre
    /// and the ears' shares, 0.9^2 + 0.35^2. The bubbles are started, not rung: rendering two
    /// million of them would take long. White water's energies are the least even (a few big,
    /// near bubbles carry most of it), so its sum is the least exact.
    #[test]
    fn every_kind_sounds_its_power() {
        let rate = 48_000.0;
        let blocks = 80_000;
        for k in 0..KINDS {
            let mut synth = WaterSynth::new(48_000, 5 + k as u32);
            let mut sources = quiet();
            sources[k] = WaterSource {
                rate: 20_000.0 / KIND[k].per_event,
                left: 1.0,
                right: 1.0,
            };
            synth.set(sources);
            let mut energy = 0.0f64;
            for _ in 0..blocks {
                synth.spawn(BLOCK);
                for b in synth.bubbles.drain(..) {
                    let a = b.y1 / (b.q.sqrt() * (TAU * b.f0 / rate).sin());
                    let ears = b.left * b.left + b.right * b.right;
                    energy += f64::from(a * a / (4.0 * damping(3.0 / b.f0)) * ears);
                }
            }
            let power = energy / (blocks * BLOCK) as f64 * f64::from(rate);
            let expected = f64::from(synth.level * synth.level * 2.0 * (0.81 + 0.1225));
            assert!(
                (power / expected - 1.0).abs() < 0.2,
                "{}: {power} against {expected}",
                k
            );
        }
        // A watt a square metre dissipated radiates 1e-7 / 2 pi of one: 42 dB, 63 dB under the
        // full scale's 105.
        let db = 10.0 * (level() * level()).log10();
        assert!((db + 63.0).abs() < 0.1, "{db}");
    }

    /// A white-water roar too dense to ring every bubble keeps its biggest bubbles whole and thins
    /// its smallest, within the bubbles' budgets.
    #[test]
    fn thinning_keeps_the_big_bubbles() {
        let mut synth = WaterSynth::new(48_000, 1);
        let mut sources = quiet();
        // 26 000 breaking events a second: 780 000 bubbles wanted.
        sources[3] = WaterSource {
            rate: 26_000.0,
            left: 6_000.0,
            right: 6_000.0,
        };
        synth.set(sources);
        let keep = synth.keep();
        let strata = &synth.strata[3];
        assert_eq!(keep[3][STRATA - 1], 1.0, "{:?}", keep[3]);
        assert!(keep[3][0] < 0.05, "{:?}", keep[3]);
        let wanted = 26_000.0 * KIND[3].per_event;
        let (started, ringing) = strata
            .iter()
            .zip(keep[3])
            .fold((0.0, 0.0), |(s, r), (st, p)| {
                let n = wanted * (st.to - st.from) * p;
                (s + n, r + n * st.ring)
            });
        assert!(
            started <= MOST_PER_SECOND && ringing <= 0.75 * BUBBLES as f32,
            "{started} a second, {ringing} at once"
        );
        // Every stratum holds an eighth of the energy, the biggest bubbles' the fewest.
        for st in strata {
            assert!(
                (st.energy - 1.0 / STRATA as f32).abs() < 0.01,
                "{}",
                st.energy
            );
        }
        assert!(strata[STRATA - 1].to - strata[STRATA - 1].from < 0.01);
    }

