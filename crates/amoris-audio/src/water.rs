/// Minnaert's frequency (Hz) of a bubble `r` metres across in water at the surface's pressure.
pub fn minnaert(r: f32) -> f32 {
    3.0 / r
}

/// van den Doel's damping (1/s) of a bubble's ring, for bubbles over 0.15 mm.
pub fn damping(r: f32) -> f32 {
    0.13 / r + 0.0072 * r.powf(-1.5)
}

/// Seconds a bubble rings, to a thousandth of its amplitude.
fn ring(r: f32) -> f32 {
    6.9 / damping(r)
}

/// The amplitude of the stereo pair's power `EFFICIENCY` of a watt a square metre spread over a
/// half space brings: the square root of the intensity over the full-scale one.
fn level() -> f32 {
    let full_scale = 1e-12 * 10f32.powf(FULL_SCALE_DB / 10.0);
    (EFFICIENCY / (TAU * full_scale)).sqrt()
}

/// The integral of r^-s from a to b.
fn mass(a: f32, b: f32, s: f32) -> f32 {
    if (s - 1.0).abs() < 1e-6 {
        (b / a).ln()
    } else {
        (b.powf(1.0 - s) - a.powf(1.0 - s)) / (1.0 - s)
    }
}

/// The radius past `a` under which r^-s holds `m`: `mass`'s inverse.
fn invert(a: f32, m: f32, s: f32) -> f32 {
    if (s - 1.0).abs() < 1e-6 {
        a * m.exp()
    } else {
        (a.powf(1.0 - s) + m * (1.0 - s)).powf(1.0 / (1.0 - s))
    }
}

/// A power law with `slopes.0` below 1 mm and `slopes.1` above, between `radii`: where its pieces
/// meet, the factor by which the second continues the first there, and the two pieces' masses.
fn pieces(radii: (f32, f32), slopes: (f32, f32)) -> (f32, f32, f32, f32) {
    const HINZE: f32 = 1e-3;
    let split = HINZE.clamp(radii.0, radii.1);
    let join = split.powf(slopes.1 - slopes.0);
    (
        split,
        join,
        mass(radii.0, split, slopes.0),
        join * mass(split, radii.1, slopes.1),
    )
}

/// A radius from the power law for a uniform `u`: the inverse of its cumulative distribution.
fn radius(u: f32, radii: (f32, f32), slopes: (f32, f32)) -> f32 {
    let (split, join, below, above) = pieces(radii, slopes);
    let m = u * (below + above);
    if m <= below || above <= 0.0 {
        invert(radii.0, m.min(below), slopes.0).clamp(radii.0, split)
    } else {
        invert(split, (m - below) / join, slopes.1).clamp(split, radii.1)
    }
}

/// The share of the power law's bubbles under `r`: the distribution `radius` inverts.
fn quantile(r: f32, radii: (f32, f32), slopes: (f32, f32)) -> f32 {
    let (split, join, below, above) = pieces(radii, slopes);
    let r = r.clamp(radii.0, radii.1);
    let m = if r <= split {
        mass(radii.0, r, slopes.0)
    } else {
        below + join * mass(split, r, slopes.1)
    };
    m / (below + above)
}

/// Bands of a kind's radii holding equal shares of its sound's energy. Thinning keeps the few
/// big bubbles that carry most of it and drops the many small ones (`WaterSynth::keep`): thinned
/// evenly, a rare big bubble made as loud as all those it stands for booms alone.
const STRATA: usize = 8;

#[derive(Clone, Copy, Default)]
struct Stratum {
    /// The quantiles of the kind's radii it spans (`radius`'s `u`).
    from: f32,
    to: f32,
    /// Its share of the kind's energy.
    energy: f32,
    /// The seconds its bubbles ring on average.
    ring: f32,
}

/// What a kind's bubbles sound like together: the factor that makes their mean energy one
/// (`a^2 / 4d` over `D^2 r^(2 EXPONENT)`), whatever its radii, and their strata.
fn shape(kind: &Kind) -> (f32, [Stratum; STRATA]) {
    // Over log r, step by step: its radius, its share of the bubbles and of their energy.
    let n = 4096;
    let (lo, hi) = kind.radii;
    let step = (hi / lo).ln() / n as f32;
    let (split, join, _, _) = pieces(kind.radii, kind.slopes);
    let at = |i: f32| lo * (i * step).exp();
    let steps: Vec<(f32, f32, f32)> = (0..n)
        .map(|i| {
            let r = at(i as f32 + 0.5);
            let density = if r <= split {
                r.powf(-kind.slopes.0)
            } else {
                join * r.powf(-kind.slopes.1)
            };
            let count = density * r;
            let energy = count * (r / 1e-3).powf(2.0 * EXPONENT) / (4.0 * damping(r));
            (r, count, energy)
        })
        .collect();
    let count: f32 = steps.iter().map(|s| s.1).sum();
    let energy: f32 = steps.iter().map(|s| s.2).sum();
    // E[D^2] = E[u^20] = 1/21.
    let norm = (21.0 * count / energy).sqrt();
    let mut strata = [Stratum::default(); STRATA];
    let (mut j, mut from) = (0, 0.0);
    let (mut held, mut rung, mut counted) = (0.0, 0.0, 0.0);
    for (i, &(r, c, e)) in steps.iter().enumerate() {
        held += e;
        rung += c * ring(r);
        counted += c;
        let last = i == n - 1;
        if last || (j < STRATA - 1 && held >= energy / STRATA as f32) {
            let to = if last {
                1.0
            } else {
                quantile(at(i as f32 + 1.0), kind.radii, kind.slopes)
            };
            strata[j] = Stratum {
                from,
                to,
                energy: held / energy,
                ring: rung / counted,
            };
            (j, from) = (j + 1, to);
            (held, rung, counted) = (0.0, 0.0, 0.0);
        }
    }
    (norm, strata)
}

/// A small deterministic random source: SplitMix64 (S. Vigna), whose successive outputs are
/// independent enough that a bubble's radius, loudness, side and start do not correlate.
struct Random(u64);

impl Random {
    fn unit(&mut self) -> f32 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^= z >> 31;
        (z >> 40) as f32 / (1u64 << 24) as f32
    }
    /// A Poisson count with mean `m`: by inversion below 30, from a normal's approximation above.
    fn poisson(&mut self, m: f32) -> u32 {
        if m <= 0.0 {
            return 0;
        }
        if m > 30.0 {
            let n = (-2.0 * self.unit().max(1e-9).ln()).sqrt() * (TAU * self.unit()).cos();
            return (m + n * m.sqrt()).round().max(0.0) as u32;
        }
        let limit = (-m).exp();
        let mut product = self.unit();
        let mut k = 0;
        while product > limit {
            product *= self.unit();
            k += 1;
        }
        k
    }
}

/// A ringing bubble: a damped resonator `y[n] = c y[n-1] - q y[n-2]`, whose `c` follows the
/// rising pitch from block to block.
#[derive(Clone, Copy, Default)]
struct Bubble {
    y1: f32,
    y2: f32,
    q: f32,
    c: f32,
    f0: f32,
    rise: f32,
    age: f32,
    left: f32,
    right: f32,
    /// Samples left before it starts, within the block it was born in.
    wait: u32,
    /// Samples left to ring (to a thousandth of its amplitude).
    remaining: u32,
}

/// The water's sound, sample by sample: plain Rust, played through kira (`WaterSoundData`) or
/// written offline.
pub struct WaterSynth {
    rate: f32,
    sources: [WaterSource; KINDS],
    bubbles: Vec<Bubble>,
    random: Random,
    level: f32,
    /// Per kind, what makes its bubbles' mean energy one, so that its sound's power is its
    /// tally's alone, and its strata (`shape`).
    norm: [f32; KINDS],
    strata: [[Stratum; STRATA]; KINDS],
}

impl WaterSynth {
    pub fn new(sample_rate: u32, seed: u32) -> WaterSynth {
        let shapes: [_; KINDS] = std::array::from_fn(|k| shape(&KIND[k]));
        WaterSynth {
            rate: sample_rate as f32,
            sources: [WaterSource::default(); KINDS],
            bubbles: Vec::with_capacity(BUBBLES),
            random: Random(u64::from(seed)),
            level: level(),
            norm: shapes.map(|s| s.0),
            strata: shapes.map(|s| s.1),
        }
    }

    pub fn set(&mut self, sources: [WaterSource; KINDS]) {
        self.sources = sources;
    }

    /// Bubbles ringing now.
    pub fn ringing(&self) -> usize {
        self.bubbles.len()
    }

    /// How much of each kind's strata to start: all of it while the bubbles fit, else what keeps
    /// the most energy for its cost, as importance sampling does (a share p of a stratum whose
    /// bubbles each carry w and cost c, p proportional to w / sqrt(c), least spreads the sound's
    /// power at a given sum of p c). A bubble costs its share of the bubbles started a second and
    /// of those ringing at once; the kept ones ring louder by 1 / sqrt(p), keeping the energy.
    fn keep(&self) -> [[f32; STRATA]; KINDS] {
        // Per stratum: bubbles a second, the cost of one, and its worth for its cost.
        let mut terms = [[(0.0f32, 0.0f32, 0.0f32); STRATA]; KINDS];
        let mut load = 0.0;
        for (k, kind) in KIND.iter().enumerate() {
            let s = self.sources[k];
            let (energy, wanted) = (s.left + s.right, s.rate * kind.per_event);
            if wanted <= 0.0 || energy <= 0.0 {
                continue;
            }
            for (j, st) in self.strata[k].iter().enumerate() {
                let share = st.to - st.from;
                if share > 0.0 {
                    let cost = st.ring / (0.75 * BUBBLES as f32) + 1.0 / MOST_PER_SECOND;
                    let worth = energy / wanted * st.energy / share;
                    terms[k][j] = (wanted * share, cost, worth / cost.sqrt());
                    load += wanted * share * cost;
                }
            }
        }
        let mut keep = [[1.0; STRATA]; KINDS];
        if load <= 1.0 {
            return keep;
        }
        // Keep whole the strata most worth their cost while the rest, kept in proportion to their
        // worth, still fit: the load is linear in that proportion.
        let mut order = [(0usize, 0usize); KINDS * STRATA];
        for (i, o) in order.iter_mut().enumerate() {
            *o = (i / STRATA, i % STRATA);
        }
        order.sort_unstable_by(|a, b| terms[b.0][b.1].2.total_cmp(&terms[a.0][a.1].2));
        let (mut whole, mut rest) = (0.0, 0.0);
        for t in terms.iter().flatten() {
            rest += t.0 * t.1 * t.2;
        }
        let mut proportion = 0.0;
        for &(k, j) in &order {
            let (bubbles, cost, worth) = terms[k][j];
            proportion = (1.0 - whole) / rest;
            if proportion * worth <= 1.0 {
                break;
            }
            whole += bubbles * cost;
            rest -= bubbles * cost * worth;
        }
        for (k, row) in keep.iter_mut().enumerate() {
            for (j, p) in row.iter_mut().enumerate() {
                *p = (proportion * terms[k][j].2).min(1.0);
            }
        }
        keep
    }

    /// Starts the bubbles a block of `n` samples brings.
    fn spawn(&mut self, n: usize) {
        let block_s = n as f32 / self.rate;
        let keep = self.keep();
        for (k, kind) in KIND.iter().enumerate() {
            let s = self.sources[k];
            let (energy, wanted) = (s.left + s.right, s.rate * kind.per_event);
            if wanted <= 0.0 || energy <= 0.0 {
                continue;
            }
            // Each bubble's mean energy: the kind's power shared by the bubbles it starts.
            let loud = self.level * (energy / wanted).sqrt() * self.norm[k];
            let left_share = s.left / energy;
            for (j, st) in self.strata[k].iter().enumerate() {
                let (share, p) = (st.to - st.from, keep[k][j]);
                if share <= 0.0 || p <= 0.0 {
                    continue;
                }
                let count = self.random.poisson(wanted * share * p * block_s);
                for _ in 0..count {
                    if self.bubbles.len() == BUBBLES {
                        break;
                    }
                    let u = st.from + self.random.unit() * share;
                    let r = radius(u, kind.radii, kind.slopes);
                    let f0 = minnaert(r);
                    if f0 >= 0.45 * self.rate {
                        continue;
                    }
                    let d = damping(r);
                    // Most bubbles sound faintly (D = u^10); loud ones are near the surface.
                    let depth = self.random.unit().powi(10);
                    let a = loud / p.sqrt() * depth * (r / 1e-3).powf(EXPONENT);
                    let w = TAU * f0 / self.rate;
                    let q = (-2.0 * d / self.rate).exp();
                    // The two ears' powers add to the bubble's: 0.9^2 + 0.35^2 is near one.
                    let to_left = self.random.unit() < left_share;
                    self.bubbles.push(Bubble {
                        y1: a * q.sqrt() * w.sin(),
                        y2: 0.0,
                        q,
                        c: 2.0 * q.sqrt() * w.cos(),
                        f0,
                        rise: kind.xi * d,
                        age: 0.0,
                        left: if to_left { 0.9 } else { 0.35 },
                        right: if to_left { 0.35 } else { 0.9 },
                        wait: (self.random.unit() * n as f32) as u32,
                        remaining: (ring(r) * self.rate) as u32 + 1,
                    });
                }
            }
        }
    }

    /// Writes `out.len()` stereo frames.
    pub fn render(&mut self, out: &mut [[f32; 2]]) {
        for chunk in out.chunks_mut(BLOCK) {
            self.spawn(chunk.len());
            chunk.fill([0.0; 2]);
            let n = chunk.len();
            for b in &mut self.bubbles {
                let start = (b.wait as usize).min(n);
                b.wait = b.wait.saturating_sub(n as u32);
                // The pitch rises as the bubble ages: f(t) = f0 (1 + xi d t).
                let w = TAU * b.f0 * (1.0 + b.rise * b.age) / self.rate;
                b.c = 2.0 * b.q.sqrt() * w.cos();
                for frame in &mut chunk[start..] {
                    let y = b.c * b.y1 - b.q * b.y2;
                    // y1 holds this sample's value; y2 the one before.
                    frame[0] += b.y1 * b.left;
                    frame[1] += b.y1 * b.right;
                    b.y2 = b.y1;
                    b.y1 = y;
                }
                let rung = (n - start) as u32;
                b.remaining = b.remaining.saturating_sub(rung);
                b.age += rung as f32 / self.rate;
            }
            self.bubbles.retain(|b| b.remaining > 0);
            // A gentle limit, never a hard clip.
            for frame in chunk.iter_mut() {
                for v in frame.iter_mut() {
                    *v = v.tanh();
                }
            }
        }
    }
}

/// The water sound's latest sources, shared with kira's audio thread.
struct Shared {
    values: [AtomicU32; KINDS * 3],
}

/// Plays a `WaterSynth` through kira; set its sources with the handle.
pub struct WaterSoundData {
    pub seed: u32,
}

pub struct WaterHandle {
    shared: Arc<Shared>,
}

impl WaterHandle {
    pub fn set(&self, sources: &[WaterSource; KINDS]) {
        for (k, s) in sources.iter().enumerate() {
            for (j, v) in [s.rate, s.left, s.right].into_iter().enumerate() {
                self.shared.values[3 * k + j].store(v.to_bits(), Ordering::Relaxed);
            }
        }
    }
}

struct WaterSound {
    synth: WaterSynth,
    shared: Arc<Shared>,
    frames: Vec<[f32; 2]>,
}

impl kira::sound::SoundData for WaterSoundData {
    type Error = std::convert::Infallible;
    type Handle = WaterHandle;

    fn into_sound(self) -> Result<(Box<dyn kira::sound::Sound>, WaterHandle), Self::Error> {
        let shared = Arc::new(Shared {
            values: std::array::from_fn(|_| AtomicU32::new(0)),
        });
        let sound = WaterSound {
            synth: WaterSynth::new(48_000, self.seed),
            shared: shared.clone(),
            frames: Vec::with_capacity(4096),
        };
        Ok((Box::new(sound), WaterHandle { shared }))
    }
}

impl kira::sound::Sound for WaterSound {
    fn process(&mut self, out: &mut [kira::Frame], dt: f64, _info: &kira::info::Info) {
        let rate = (1.0 / dt).round() as f32;
        if (rate - self.synth.rate).abs() > 0.5 {
            self.synth.rate = rate;
        }
        let v = |i: usize| f32::from_bits(self.shared.values[i].load(Ordering::Relaxed));
        self.synth.set(std::array::from_fn(|k| WaterSource {
            rate: v(3 * k),
            left: v(3 * k + 1),
            right: v(3 * k + 2),
        }));
        // The buffer grows only when the backend asks for more frames than ever before.
        self.frames.resize(out.len(), [0.0; 2]);
        self.synth.render(&mut self.frames);
        for (o, f) in out.iter_mut().zip(&self.frames) {
            *o = kira::Frame {
                left: f[0],
                right: f[1],
            };
        }
    }

    fn finished(&self) -> bool {
        false
    }
}

