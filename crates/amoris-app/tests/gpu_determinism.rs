//! The deterministic water kernels on this machine's GPU (water.md 66): the samples' GPU water,
//! stepped from their scenes, holds after every tick the field whose digests `golden/water-digests.txt`
//! records, on every adapter, driver and backend. `AMORIS_BACKEND=vulkan` and
//! `AMORIS_GPU_MINIMAL=features,limits,timestamps` run it on another backend or the WebGPU baseline,
//! `tools/water_determinism_check.mjs` in Chrome (with `--adapter swiftshader`, on the CPU), and
//! `AMORIS_BLESS=1` rewrites the record after a kernel changes.
#[path = "../src/water_compute.rs"]
mod water_compute;
use amoris_link::Source;
use amoris_runtime::{Command, Game, Project};
use serde_json::json;
use std::sync::Arc;

/// The samples and how many ticks of each: a pool and a party of boats, a river with its fall, the
/// surf with its sea, dispersion and plunging crests, a shore, floaters and their feedback, the
/// valley's joined regions over a terrain, and a harbour basin under a gusting gale and rain.
const SAMPLES: &[(&str, u64)] = &[
    ("water-resident", 300),
    ("pool-party", 300),
    ("river-falls", 300),
    ("surf-beach", 600),
    ("water-shore", 300),
    ("water-floaters", 300),
    ("water-feedback", 300),
    ("water-valley", 300),
    ("water-storm", 300),
];

fn golden() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/water-digests.txt")
}

fn command(g: &mut Game, name: &str, params: serde_json::Value) -> serde_json::Value {
    g.apply(&Command::new(Source::Developer(0), 1, name, params))
        .unwrap_or_else(|e| panic!("{name}: {e:?}"))
}

/// Each region's digests after ticks 1..=ticks, its first 8 hex digits: one line per region.
fn run(sample: &str, ticks: u64) -> Vec<String> {
    let setup = Project::load(
        &std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../samples")
            .join(sample),
    )
    .unwrap()
    .setup(false)
    .unwrap();
    let mut g = water_compute::builder(Arc::new(setup), 1).build().unwrap();
    let regions: Vec<u64> = command(&mut g, "world.query", json!({"with": ["WaterRegion"]}))
        .as_array()
        .unwrap()
        .iter()
        .map(|e| e["id"].as_u64().unwrap())
        .collect();
    let mut lines: Vec<String> = regions
        .iter()
        .map(|id| format!("{sample} {id} {ticks}:"))
        .collect();
    for _ in 0..ticks {
        let r = g.step().unwrap();
        assert!(r.errors.is_empty(), "{sample}: {:?}", r.errors);
        for (line, id) in lines.iter_mut().zip(&regions) {
            let v = command(
                &mut g,
                "world.get",
                json!({"entity": id, "fields": ["WaterResident"]}),
            );
            let digest = &v["fields"]["WaterResident"]["recipe"]["digest"];
            let hex: String = digest.as_array().map_or_else(String::new, |d| {
                d[..4]
                    .iter()
                    .map(|b| format!("{:02x}", b.as_u64().unwrap()))
                    .collect()
            });
            line.push(' ');
            line.push_str(if hex.is_empty() { "-" } else { &hex });
        }
    }
    lines
}

#[test]
fn every_device_steps_the_samples_water_to_the_same_bits() {
    std::thread::Builder::new()
        .stack_size(amoris_runtime::GAME_STACK_BYTES)
        .spawn(|| {
            let mut lines = vec![
                "# Generated by tests/gpu_determinism.rs (AMORIS_BLESS=1 rewrites it; water.md 66): each"
                    .to_string(),
                "# GPU water region's field digest after every tick, its first 8 hex digits, the same on"
                    .to_string(),
                "# every device. A line: sample, region entity, ticks, then a digest for each tick."
                    .to_string(),
            ];
            for (sample, ticks) in SAMPLES {
                lines.extend(run(sample, *ticks));
            }
            let text = lines.join("\n") + "\n";
            if std::env::var_os("AMORIS_BLESS").is_some() {
                std::fs::write(golden(), &text).unwrap();
                return;
            }
            let expected = std::fs::read_to_string(golden()).unwrap();
            for (want, got) in expected.lines().zip(text.lines()).filter(|(w, _)| !w.starts_with('#')) {
                if want != got {
                    let (w, g): (Vec<_>, Vec<_>) =
                        (want.split(' ').collect(), got.split(' ').collect());
                    let tick = w.iter().zip(&g).skip(3).position(|(a, b)| a != b).map(|t| t + 1);
                    panic!(
                        "{} {}: this device's field first differs from the record after tick {tick:?}",
                        g[0], g[1]
                    );
                }
            }
            assert_eq!(expected.lines().count(), text.lines().count(), "the record's samples");
        })
        .unwrap()
        .join()
        .unwrap();
}

/// What the deterministic kernels cost (liquids.md 18): the wall time of a tick, its GPU work and
/// readbacks waited for, over ticks 61 to 360 of the heavier samples. The same test built against
/// a commit before them gives the f32 kernels' times. `cargo test --release -p amoris-app --test
/// gpu_determinism time_samples -- --ignored --nocapture`.
#[test]
#[ignore]
#[allow(clippy::disallowed_methods)] // the test's own clock stands outside every tick
fn time_samples() {
    std::thread::Builder::new()
        .stack_size(amoris_runtime::GAME_STACK_BYTES)
        .spawn(|| {
            for sample in ["surf-beach", "river-falls", "pool-party", "water-valley"] {
                let setup = Project::load(
                    &std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                        .join("../../samples")
                        .join(sample),
                )
                .unwrap()
                .setup(false)
                .unwrap();
                let mut g = water_compute::builder(Arc::new(setup), 1).build().unwrap();
                for _ in 0..60 {
                    g.step().unwrap();
                }
                let start = std::time::Instant::now();
                for _ in 0..300 {
                    g.step().unwrap();
                }
                eprintln!(
                    "{sample}: {:.3} ms a tick",
                    start.elapsed().as_secs_f64() * 1e3 / 300.0
                );
            }
        })
        .unwrap()
        .join()
        .unwrap();
}
